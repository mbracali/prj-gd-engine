#include "platform/app_icon.h"

#include <SDL3/SDL.h>

#include <cstddef>
#include <cstring>

extern const unsigned char kGd01IconPng[];  // gd01_icon_data.cpp, generated by CMake
extern const std::size_t kGd01IconPngSize;

namespace {

SDL_Surface* loadIcon() {
    SDL_IOStream* io = SDL_IOFromConstMem(kGd01IconPng, kGd01IconPngSize);
    if (!io) return nullptr;
    SDL_Surface* png = SDL_LoadPNG_IO(io, true);
    if (!png) return nullptr;
    SDL_Surface* rgba = SDL_ConvertSurface(png, SDL_PIXELFORMAT_RGBA32);
    SDL_DestroySurface(png);
    return rgba;
}

}  // namespace

void setAppWindowIcon(SDL_Window* window) {
#ifndef __ANDROID__
    if (!window) return;
    if (SDL_Surface* icon = loadIcon()) {
        SDL_SetWindowIcon(window, icon);
        SDL_DestroySurface(icon);
    }
#else
    (void)window;
#endif
}

bool appIconImage(Image& out) {
    SDL_Surface* icon = loadIcon();
    if (!icon) return false;
    out.width = icon->w, out.height = icon->h;
    out.rgba.resize(size_t(icon->w) * size_t(icon->h) * 4);
    for (int y = 0; y < icon->h; ++y)
        std::memcpy(out.rgba.data() + size_t(y) * size_t(icon->w) * 4,
                    static_cast<const unsigned char*>(icon->pixels) + size_t(y) * size_t(icon->pitch), size_t(icon->w) * 4);
    SDL_DestroySurface(icon);
    return true;
}
