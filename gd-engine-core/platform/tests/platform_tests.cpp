uint8_t chdImageByte(uint64_t at) {
    const uint32_t s = uint32_t(at / 2048), i = uint32_t(at % 2048);
    if (i < 4) return uint8_t(s >> (8 * i));
    if (i == 100 + s) return 0xA5;
    return uint8_t(s * 37);
}

void checkChdImage(gd::core::selftest::Context& ctx, p::RandomAccessFile& f, const char* what) {
    GDCORE_CHECK_MSG(f.size() == 40 * 2048, std::string(what) + ": size " + std::to_string(f.size()));
    std::vector<uint8_t> all(size_t(f.size()));
    GDCORE_CHECK(f.read(0, all.data(), all.size()));
    size_t bad = 0;
    for (size_t i = 0; i < all.size(); ++i) bad += all[i] != chdImageByte(i);
    GDCORE_CHECK_MSG(bad == 0, std::string(what) + ": " + std::to_string(bad) + " bytes differ");
    uint8_t b[3000];  // across a sector (and a DVD hunk) boundary
    GDCORE_CHECK(f.read(4096 - 1000, b, sizeof(b)) && b[0] == chdImageByte(3096) && b[2999] == chdImageByte(6095));
    GDCORE_CHECK(!f.read(f.size() - 1, b, 2));  // past the end
}

